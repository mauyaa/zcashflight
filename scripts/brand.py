"""Builds every brand asset from two sources:
  brand/logo/zcashflight-mark.svg   the Z mark, the project's only logo
  brand/fonts/Michroma-Regular.ttf  the typeface of the name (SIL OFL), drawn as outlines
The name is a lockup: the mark is the Z, followed by CASHFLIGHT. The mark is scaled to the letters'
cap height and spaced from the C exactly as Michroma spaces its own Z from C, so it reads as one word.
Outlines, not live text, so the header, favicon and standalone reports look identical everywhere.
Needs fontTools at build time only:  pip install fonttools  then  python scripts/brand.py ui/brand src/brand.ts"""
import re
import sys
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.transformPen import TransformPen

FONT = 'brand/fonts/Michroma-Regular.ttf'
MARK = 'brand/logo/zcashflight-mark.svg'
TRACK = 0.06  # letter-spacing, in em
LIME, IVORY, NAVY = '#c5f48d', '#eef1ea', '#111c27'

def mark():
    s = open(MARK, encoding='utf8').read()
    w, h = map(float, re.search(r'viewBox="0 0 ([\d.]+) ([\d.]+)"', s).groups())
    return re.search(r' d="([^"]+)"', s).group(1), w, h

def lockup():
    """The mark as the Z, then CASHFLIGHT. Returns (mark transform, letters path, width, height) in font units."""
    f = TTFont(FONT); gs = f.getGlyphSet(); cmap = f.getBestCmap(); upm = f['head'].unitsPerEm
    cap = f['OS/2'].sCapHeight or int(upm * 0.7)
    ink = lambda ch: (lambda p: (gs[cmap[ord(ch)]].draw(p), p.bounds)[1])(BoundsPen(gs))
    z, c = ink('Z'), ink('C')
    gap = (f['hmtx'][cmap[ord('Z')]][0] - z[2]) + upm * TRACK + c[0]  # Michroma's own Z-to-C ink gap
    _, mw, mh = mark()
    s = cap / mh                                    # the mark's flat top and bottom sit on cap height and baseline
    pen = SVGPathPen(gs); x = mw * s + gap - c[0]   # first letter's origin, so its ink starts one gap after the mark
    for ch in 'CASHFLIGHT':
        g = cmap[ord(ch)]
        gs[g].draw(TransformPen(pen, (1, 0, 0, -1, x, cap)))  # flip y, baseline at cap height
        x += f['hmtx'][g][0] + upm * TRACK
    last = ink('T'); width = x - upm * TRACK - (f['hmtx'][cmap[ord('T')]][0] - last[2])
    return f'scale({s:.5f})', pen.getCommands(), width, cap

def write(path, text):
    open(path, 'w', encoding='utf8', newline='\n').write(text)

if __name__ == '__main__':
    out = sys.argv[1]
    md, mw, mh = mark()
    mt, letters, w, h = lockup()
    for name, fill in (('ivory', IVORY), ('navy', NAVY), ('current', 'currentColor')):
        write(f'{out}/logo-{name}.svg',
              f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {w:.0f} {h}" role="img" aria-label="ZcashFlight">'
              f'<title>ZcashFlight</title><path fill="{LIME}" transform="{mt}" d="{md}"/><path fill="{fill}" d="{letters}"/></svg>\n')
    for name in ('ivory', 'navy'):
        write(f'brand/logo/zcashflight-logo-{name}.svg', open(f'{out}/logo-{name}.svg', encoding='utf8').read())
    write(f'{out}/mark.svg', open(MARK, encoding='utf8').read())
    # app icon and favicon: the mark alone on a navy rounded square, 62% of the width, centred
    s = 256 * 0.62 / mw
    icon = (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 256 256"><rect width="256" height="256" rx="56" fill="{NAVY}"/>'
            f'<path fill="{LIME}" transform="translate({(256 - mw * s) / 2:.2f} {(256 - mh * s) / 2:.2f}) scale({s:.5f})" d="{md}"/></svg>\n')
    write(f'{out}/icon.svg', icon)
    write('brand/logo/zcashflight-icon.svg', icon)
    if len(sys.argv) > 2:  # the TypeScript constant used by HTML reports
        write(sys.argv[2], "// Generated by scripts/brand.py. The ZcashFlight logo: the Z mark, then CASHFLIGHT in Michroma (SIL OFL).\n"
              f"export const LOGO = {{ width: {w:.0f}, height: {h}, markFill: '{LIME}', markTransform: '{mt}', mark: '{md}', letters: '{letters}' }};\n")
    print(f'brand assets written: logo {w:.0f} x {h}')
