// Records real ZcashFlight runs of the ZecShop sample for the hosted demo (ui/recorded/).
// Nothing here is hand-written: seeded run, fixed run, a regression, and the failure states all come from the engine.
//   node scripts/record.ts

import { cpSync, mkdtempSync, rmSync, mkdirSync, writeFileSync } from 'node:fs';
import { createServer } from 'node:http';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';
import { loadPolicy } from '../src/engine/policy.ts';
import { runPolicy, type Progress } from '../src/engine/runner.ts';
import { compareRuns, listRuns } from '../src/engine/store.ts';
import { markdown, html, sarif } from '../src/engine/report.ts';
import type { Run } from '../src/engine/types.ts';
import { REPO } from '../src/meta.ts';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const OUT = join(ROOT, 'ui', 'recorded');
const work = mkdtempSync(join(tmpdir(), 'zcashflight-record-'));
cpSync(join(ROOT, 'examples', 'zecshop'), work, { recursive: true, filter: s => !/[\\/](\.zcashflight|logs|data)([\\/]|$)/.test(s) });
const fixes = (m: 'apply' | 'reset') => spawnSync(process.execPath, [join(work, 'scripts', 'fixes.ts'), m], { cwd: work, stdio: 'ignore' });
const policy = () => loadPolicy(join(work, 'zcashflight.yml'));

async function recorded(signalAfter?: string): Promise<{ run: Run; progress: { ms: number; e: Progress }[] }> {
  const t0 = Date.now(), progress: { ms: number; e: Progress }[] = [];
  const abort = new AbortController();
  const run = await runPolicy(policy(), { signal: abort.signal, onProgress: e => {
    if (e.type === 'captured' && progress.length && progress[progress.length - 1].e.type === 'captured' && JSON.stringify(progress[progress.length - 1].e) === JSON.stringify(e)) return;
    progress.push({ ms: Date.now() - t0, e });
    if (signalAfter && e.type === 'step' && e.scenario === signalAfter) abort.abort();
  } });
  return { run, progress };
}

fixes('reset');
const seeded = await recorded();
fixes('apply');
const fixed = await recorded();
// a later change brings one leak back: the error reporter starts sending the memo again
cpSync(join(work, 'seeded', 'lib', 'errors.ts'), join(work, 'lib', 'errors.ts'));
const regressed = await recorded();
cpSync(join(work, 'fixes', 'lib', 'errors.ts'), join(work, 'lib', 'errors.ts'));

// failure states, produced for real
const blocker = createServer((_q, s) => s.end('not zecshop'));
await new Promise<void>(r => blocker.listen(4600, '127.0.0.1', () => r()));
const nostart = await recorded();
blocker.close();
const stopped = await recorded('checkout');

const p = policy();
const runs = listRuns(work);
mkdirSync(OUT, { recursive: true });
for (const r of [seeded.run, fixed.run]) {
  const prev = runs.filter(x => x.n < r.n && x.status === 'complete').pop();
  const cmp = r === fixed.run ? compareRuns(seeded.run, r) : prev ? compareRuns(prev, r) : undefined;
  writeFileSync(join(OUT, `report-${r.n}.html`), html(r, cmp));
  writeFileSync(join(OUT, `report-${r.n}.md`), markdown(r, cmp));
  writeFileSync(join(OUT, `report-${r.n}.sarif`), JSON.stringify(sarif(r), null, 2));
  writeFileSync(join(OUT, `report-${r.n}.json`), JSON.stringify(r, null, 2));
}
const err = (r: Run, code: string) => ({ code, message: r.error, detail: (r.error ?? '').includes('already listening') ? 'port 4600 is already in use' : undefined });
writeFileSync(join(OUT, 'data.json'), JSON.stringify({
  recordedAt: new Date().toISOString(),
  project: { name: 'ZecShop', path: 'examples/zecshop', policyFile: 'zcashflight.yml', sample: true, running: false },
  policy: {
    protect: p.protect, network: p.network,
    destinations: p.destinations.map(d => ({ host: d.host, purpose: d.purpose, allow: d.allow })),
    scenarios: p.scenarios.map(s => ({ name: s.name, description: s.description, steps: s.steps.length })),
    logs: p.logs.map(l => l.path), notTested: p.notTested, start: p.app.start,
  },
  seeded: seeded.run, progress: seeded.progress,
  fixed: fixed.run, fixedProgress: fixed.progress, comparison: compareRuns(seeded.run, fixed.run),
  regressed: regressed.run, regressedAdded: compareRuns(fixed.run, regressed.run).added.map(f => f.id),
  errors: { nostart: err(nostart.run, 'nostart'), stopped: err(stopped.run, 'stopped') },
  history: [seeded.run, fixed.run].map(r => ({ n: r.n, finishedAt: r.finishedAt, status: r.status, findings: r.findings.length, fingerprint: r.fingerprint, requests: r.stats.requests })),
}, null, 1));
writeFileSync(join(ROOT, 'ui', 'config.js'), [
  '// Generated by `npm run record` from src/meta.ts. Links shown in the dashboard header.',
  `window.ZF_CONFIG = ${JSON.stringify({ repo: REPO, docs: `${REPO}/blob/main/docs/start/quickstart.md` })};`, '',
].join('\n'));
rmSync(work, { recursive: true, force: true });
console.log(`recorded: seeded ${seeded.run.findings.length} findings, fixed ${fixed.run.findings.length}, regressed ${regressed.run.findings.length}, nostart "${nostart.run.error}", stopped "${stopped.run.error}"`);
