"""Draws the ZCASHFLIGHT wordmark from Michroma (SIL OFL, brand/fonts/Michroma-Regular.ttf) as SVG outlines.
Outlines, not live text, so the favicon and standalone reports look identical everywhere.
Needs fontTools at build time only:  pip install fonttools  then  python scripts/wordmark.py <outdir>"""
import sys
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen

FONT = 'brand/fonts/Michroma-Regular.ttf'
TRACK = 0.06  # letter-spacing, in em

def outline(text):
    f = TTFont(FONT); gs = f.getGlyphSet(); cmap = f.getBestCmap(); upm = f['head'].unitsPerEm
    cap = f['OS/2'].sCapHeight or int(upm * 0.7)
    pen = SVGPathPen(gs); x = 0
    for ch in text:
        g = cmap[ord(ch)]
        gs[g].draw(TransformPen(pen, (1, 0, 0, -1, x, cap)))  # flip y, baseline at cap height
        x += f['hmtx'][g][0] + upm * TRACK
    x -= upm * TRACK
    return pen.getCommands(), x, cap

def svg(text, fill, title):
    d, w, h = outline(text)
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {w:.0f} {h}" role="img" aria-label="{title}">'
            f'<title>{title}</title><path fill="{fill}" d="{d}"/></svg>\n'), d, w, h

if __name__ == '__main__':
    out = sys.argv[1]
    for name, fill in (('ivory', '#eef1ea'), ('navy', '#111c27'), ('current', 'currentColor')):
        open(f'{out}/wordmark-{name}.svg', 'w', encoding='utf8').write(svg('ZCASHFLIGHT', fill, 'ZcashFlight')[0])
    _, d, w, h = svg('ZF', '#eef1ea', 'ZcashFlight')
    s = 200 / w
    open(f'{out}/icon.svg', 'w', encoding='utf8').write(
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 256 256"><rect width="256" height="256" rx="56" fill="#111c27"/>'
        f'<path fill="#eef1ea" transform="translate(28 {(256 - h * s) / 2:.2f}) scale({s:.5f})" d="{d}"/></svg>\n')
    if len(sys.argv) > 2:  # also write the TypeScript constant used by reports
        dd, ww, hh = outline('ZCASHFLIGHT')
        open(sys.argv[2], 'w', encoding='utf8', newline='\n').write(
            "// Generated by scripts/wordmark.py from Michroma (SIL OFL). The ZCASHFLIGHT wordmark as one SVG path.\n"
            f"export const WORDMARK = {{ width: {ww:.0f}, height: {hh}, d: '{dd}' }};\n")
    print('wordmark written')
